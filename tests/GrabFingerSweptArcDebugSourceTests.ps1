if ($failures.Count -gt 0) {
    Write-Host 'Grab finger swept-arc debug boundary failed:'
    foreach ($failure in $failures) {
        Write-Host " - $failure"
    }
    exit 1
}

Write-Host 'Grab finger swept-arc debug boundary passed.'
